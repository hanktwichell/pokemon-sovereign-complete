#ifndef POKEPLATINUM_COMPLETE_MAP_INFO_H
#define POKEPLATINUM_COMPLETE_MAP_INFO_H

#include "generated/map_headers.h"

#include "field/field_system_decl.h"
#include "struct_decls/map_object.h"

#include "map_matrix.h"
#include "savedata.h"

// Sovereign Complete: what HeartGold's map headers say that Platinum's don't, for Johto and Kanto's maps
// (MAP_HEADER_HGSS_*): where following Pokémon may follow, the region, the Pokégear's world map position, phone calls
// and radio. Sinnoh's maps get defaults: Sinnoh, no Pokégear data, and following as in HeartGold's buildings and
// outdoors. The data is include/data/hgss_map_info.h, generated by tools/complete/import_hgss_headers.py.
#define MAP_HEADER_HGSS_FIRST MAP_HEADER_HGSS_EVERYWHERE

enum FollowMode {
    FOLLOW_MODE_PREVENT = 0, // nobody follows
    FOLLOW_MODE_HEIGHT_RESTRICT, // only small Pokémon follow (indoors)
    FOLLOW_MODE_ALLOW,
};

enum MapRegion {
    MAP_REGION_JOHTO = 0,
    MAP_REGION_KANTO,
    MAP_REGION_SINNOH,
};

BOOL MapHeader_IsHGSS(enum MapHeaderID mapHeaderID);
// On an overworld matrix: Sinnoh's (MapHeader_IsOnMainMatrix) or Johto and Kanto's. The Town Map, the Pokétch and the
// Underground keep MapHeader_IsOnMainMatrix, as they show or lead to Sinnoh.
BOOL MapHeader_IsOnOverworldMatrix(enum MapHeaderID mapHeaderID);
enum FollowMode MapHeader_GetFollowMode(enum MapHeaderID mapHeaderID);
enum MapRegion MapHeader_GetRegion(enum MapHeaderID mapHeaderID);
void MapHeader_GetWorldMapPos(enum MapHeaderID mapHeaderID, int *x, int *y);
u32 MapHeader_GetMomCallIntroParam(enum MapHeaderID mapHeaderID);
BOOL MapHeader_HasOutgoingCalls(enum MapHeaderID mapHeaderID);
BOOL MapHeader_HasIncomingCalls(enum MapHeaderID mapHeaderID);
BOOL MapHeader_HasRadioSignal(enum MapHeaderID mapHeaderID);
// HeartGold's changes to the overworld's blocks as a map loads: Mahogany Town's antenna tree, the Lake of Rage's level
void CompleteMapInfo_LoadMatrix(MapMatrix *mapMatrix, SaveData *saveData, enum MapHeaderID mapHeaderID);
// Whether the Lake of Rage is low today, seen from this map (its water level, and a clear sky over the lake)
BOOL CompleteMapInfo_IsLakeOfRageLow(SaveData *saveData, enum MapHeaderID mapHeaderID);
// HeartGold's boulder holes, after a Strength push: a boulder pushed onto its hole on Ice Path B1F falls through (its
// flag set, the object gone) and shows on B2F (its fallen flag cleared). TRUE if it fell.
BOOL CompleteMapInfo_BoulderFell(FieldSystem *fieldSystem, MapObject *boulder);

#endif // POKEPLATINUM_COMPLETE_MAP_INFO_H
