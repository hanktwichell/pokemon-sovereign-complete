#!/usr/bin/env python3
"""Write HeartGold's Bug-Catching Contest tables as C (decomp/include/data/complete_bug_contest.h), for
src/complete_bug_contest.c.

HeartGold reads them from two loose files (data/mushi/mushi_encount.bin and mushi_trainer.bin), built from the CSVs
in its files/data/mushi/; Sacred Gold's ROM has the same bytes. The tables:
- sBugContestEncounters: four sets of ten (no National Dex; then Tuesday, Thursday, Saturday with it), each a species,
  its levels, its slot's roll threshold and its species score. A roll of 0-99 picks the first slot it is at least.
- sBugContestantEntries: the ten contestants' eight entries each (whether it needs the National Dex, its weekday or
  7 for any day, the species, the score and how far it varies).

Usage, from the repo root: python3 tools/complete/import_hgss_bug_contest.py
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_hgss_headers import write_if_changed  # noqa: E402
from import_hgss_maps import DECOMP, HG  # noqa: E402

OUT = 'include/data/complete_bug_contest.h'
ENCOUNTER_SETS, ENCOUNTERS_PER_SET = 4, 10
CONTESTANTS, ENTRIES_PER_CONTESTANT = 10, 8


def rows(name):
    return list(csv.DictReader(open(os.path.join(HG, 'files/data/mushi', name))))


def main():
    encounters, entries = rows('mushi_encount.csv'), rows('mushi_trainer.csv')
    assert len(encounters) == ENCOUNTER_SETS * ENCOUNTERS_PER_SET, len(encounters)
    assert len(entries) == CONTESTANTS * ENTRIES_PER_CONTESTANT, len(entries)
    out = ['// Generated by tools/complete/import_hgss_bug_contest.py from HeartGold\'s files/data/mushi; do not edit.',
           '#ifndef POKEPLATINUM_DATA_COMPLETE_BUG_CONTEST_H',
           '#define POKEPLATINUM_DATA_COMPLETE_BUG_CONTEST_H',
           '',
           f'static const BugContestEncounter sBugContestEncounters[{ENCOUNTER_SETS}][{ENCOUNTERS_PER_SET}] = {{']
    for s in range(ENCOUNTER_SETS):
        out.append('    {')
        for r in encounters[s * ENCOUNTERS_PER_SET:(s + 1) * ENCOUNTERS_PER_SET]:
            out.append(f'        {{ {r["species"]}, {r["lvlmin"]}, {r["lvlmax"]}, {r["rate"]}, {r["score"]} }},')
        out.append('    },')
    out += ['};', '', f'static const BugContestantEntry sBugContestantEntries[{CONTESTANTS}][{ENTRIES_PER_CONTESTANT}] = {{']
    for c in range(CONTESTANTS):
        out.append('    {')
        for r in entries[c * ENTRIES_PER_CONTESTANT:(c + 1) * ENTRIES_PER_CONTESTANT]:
            out.append(f'        {{ {r["national"]}, {r["day"]}, {r["species"]}, {r["score"]}, {r["randmod"]} }},')
        out.append('    },')
    out += ['};', '', '#endif', '']
    write_if_changed(os.path.join(DECOMP, OUT), '\n'.join(out))
    print(f'{OUT}: {len(encounters)} encounters, {len(entries)} contestant entries')


if __name__ == '__main__':
    main()
