#!/usr/bin/env python3
"""Bring in HeartGold's 3D effects for its gyms (src/complete_gyms.c), as archives the engine loads:

- Viridian Gym's arrow tiles light up as the player steps onto them: HeartGold's a/2/5/5 (its viridian.c), four
  models (members 4-7, one for each arrow's direction) and their texture animations (members 0-3), packed as they are
  into decomp/res/prebuilt/fielddata/complete_gym_effects/viridian_gym.narc
  (NARC_INDEX_FIELDDATA__COMPLETE__VIRIDIAN_GYM).
- Fuchsia Gym's invisible walls flash where the player bumps into them: HeartGold's a/2/4/6 (its fuchsia.c), twelve
  wall pieces' models (members 0-11) and four animations for each (12 + 12 * k + model), packed as they are into
  fuchsia_gym.narc (NARC_INDEX_FIELDDATA__COMPLETE__FUCHSIA_GYM), and its table of the 60 wall tiles (each one's
  piece, its offset and the neighbouring tiles whose flash it stops) into decomp/include/data/hgss_fuchsia_gym_walls.h.

Usage: python3 tools/complete/import_hgss_gym_effects.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_hgss_maps import DECOMP, HG  # noqa: E402
from narc import read_narc, write_narc  # noqa: E402

OUT = os.path.join(DECOMP, 'res/prebuilt/fielddata/complete_gym_effects')
ARCHIVES = {'viridian_gym.narc': 'files/a/2/5/5', 'fuchsia_gym.narc': 'files/a/2/4/6'}
WALLS_SOURCE = 'src/field/gymmick/fuchsia.c'
WALLS_HEADER = os.path.join(DECOMP, 'include/data/hgss_fuchsia_gym_walls.h')


def fuchsia_walls():
    """HeartGold's sWallData: [(x, z, model, x offset, z offset, [neighbours])]."""
    text = open(os.path.join(HG, WALLS_SOURCE), encoding='utf-8').read()
    body = text[text.index('sWallData[] = {'):]
    body = body[:body.index('\n};')]
    entry = (r'\.x = (\d+),\s*\.z = (\d+),\s*\.modelId = (\d+),\s*\.xOffset = (-?\d+),\s*\.zOffset = (-?\d+),\s*'
             r'\.neighbors = \{([^}]*)\}')
    return [(int(x), int(z), int(model), int(dx), int(dz), [int(n) for n in neighbours.split(',') if n.strip()])
            for x, z, model, dx, dz, neighbours in re.findall(entry, body)]


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, source in ARCHIVES.items():
        members = read_narc(os.path.join(HG, source))
        write_narc(os.path.join(OUT, name), members)
        print(f'{name}: {len(members)} files from {source}')
    walls = fuchsia_walls()
    lines = ['// Generated by tools/complete/import_hgss_gym_effects.py from HeartGold\'s ' + WALLS_SOURCE + ': Fuchsia',
             '// Gym\'s invisible wall tiles, each with its piece\'s model, the model\'s offset in tiles and the wall tiles',
             '// next to it (-1 past the last).',
             'static const CompleteFuchsiaWall sFuchsiaWalls[] = {']
    for x, z, model, dx, dz, neighbours in walls:
        lines.append(f'    {{ {x}, {z}, {model}, {dx}, {dz}, {{ {", ".join(str(n) for n in neighbours)} }} }},')
    lines.append('};')
    with open(WALLS_HEADER, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(walls)} wall tiles into {os.path.relpath(WALLS_HEADER, DECOMP)}')


if __name__ == '__main__':
    main()
