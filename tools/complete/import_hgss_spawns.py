#!/usr/bin/env python3
"""Bring in HeartGold's spawn points (its sSpawnMaps, asm/unk_0203BA5C.s): where the player comes back after blacking
out, and the town each Fly point lands in.

Platinum keeps the same in src/spawn_locations.c (sSpawnLocations: a warp ID is its row + 1), whose Pokémon Centers set
the blackout warp as the player enters them (GetMapBlackOutWarpId). HeartGold's 30 rows follow Platinum's 20, in
HeartGold's order (SPAWN_NEW_BARK first), so its SPAWN_X is warp ID SPAWN_HGSS_FIRST - 1 + its number:

- include/data/hgss_spawn_locations.h: the rows, which spawn_locations.c includes at the end of its table. A row that
  is a blackout spawn in HeartGold (its Pokémon Centers, the player's house, the League's entrance) is one here
  (isWarpPos). The Fly points don't unlock yet (unlockOnMapEntry 0): Fly over Johto and Kanto comes with the
  three-region Town Map (step 7). HeartGold's maps keep its coordinates (its matrices and interiors).
- include/constants/hgss_spawns.h: SPAWN_HGSS_X for each, for the translated scripts (HeartGold's SetSpawn).

Usage: python3 tools/complete/import_hgss_spawns.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_hgss_maps import DECOMP, HG  # noqa: E402

SPAWNS_ASM = os.path.join(HG, 'asm', 'unk_0203BA5C.s')
SPAWNS_H = os.path.join(HG, 'include', 'constants', 'spawns.h')
PLATINUM = os.path.join(DECOMP, 'src', 'spawn_locations.c')
ROWS_OUT = os.path.join(DECOMP, 'include', 'data', 'hgss_spawn_locations.h')
CONSTANTS_OUT = os.path.join(DECOMP, 'include', 'constants', 'hgss_spawns.h')


def platinum_rows():
    """How many rows Platinum's own table has (the rows before the include of HeartGold's)."""
    text = open(PLATINUM, encoding='utf-8').read()
    table = text[text.index('sSpawnLocations[] = {'):]
    table = table[:table.index('#include "data/hgss_spawn_locations.h"') if 'hgss_spawn_locations' in table
                  else table.index('};')]
    return len(re.findall(r'^\s+\{ MAP_HEADER_', table, re.M))


def hg_spawns():
    """[(SPAWN_X name, row values)] in HeartGold's order."""
    names = {int(n): name for name, n in re.findall(r'#define (SPAWN_\w+)\s+(\d+)', open(SPAWNS_H).read())}
    rows = re.findall(r'^\s+spawn (.*)$', open(SPAWNS_ASM).read(), re.M)
    out = []
    for i, row in enumerate(rows, 1):
        flag, blackout, fly, map_, x, z, fly_map, fly_x, fly_z = [v.strip() for v in row.split(',')][:9]
        out.append((names[i], int(blackout), map_, int(x, 0), int(z, 0), fly_map, int(fly_x, 0), int(fly_z, 0)))
    return out


def main():
    first = platinum_rows() + 1
    spawns = hg_spawns()
    header = lambda m: f'MAP_HEADER_HGSS_{m[len("MAP_"):]}'  # noqa: E731
    rows = [f'// Generated by tools/complete/import_hgss_spawns.py: HeartGold\'s spawn points, after Platinum\'s (warp IDs',
            f'// {first} to {first + len(spawns) - 1}). Fly points unlock with the three-region Town Map (step 7).']
    for name, blackout, map_, x, z, fly_map, fly_x, fly_z in spawns:
        rows.append(f'{{ {header(map_)}, {x:#x}, {z:#x}, {header(fly_map)}, {fly_x:#x}, {fly_z:#x}, {blackout:#x}, 0x0, 0 }},'
                    f' // {name}')
    open(ROWS_OUT, 'w').write('\n'.join(rows) + '\n')
    consts = ['#ifndef POKEPLATINUM_CONSTANTS_HGSS_SPAWNS_H', '#define POKEPLATINUM_CONSTANTS_HGSS_SPAWNS_H', '',
              '// Generated by tools/complete/import_hgss_spawns.py: the warp ID of each of HeartGold\'s spawn points',
              '// (src/spawn_locations.c), for SetBlackOutWarpId.', f'#define SPAWN_HGSS_FIRST {first}']
    consts += [f'#define SPAWN_HGSS_{name[len("SPAWN_"):]} {first + i}' for i, (name, *_) in enumerate(spawns)]
    consts += [f'#define SPAWN_HGSS_COUNT {len(spawns)}', '', '#endif // POKEPLATINUM_CONSTANTS_HGSS_SPAWNS_H']
    open(CONSTANTS_OUT, 'w').write('\n'.join(consts) + '\n')
    print(f'{len(spawns)} spawn points (warp IDs {first} to {first + len(spawns) - 1}), '
          f'{sum(s[1] for s in spawns)} of them blackout spawns')


if __name__ == '__main__':
    main()
