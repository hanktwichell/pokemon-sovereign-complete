#!/usr/bin/env python3
"""HeartGold's Battle Frontier move tutors (pokeheartgold's src/field/scrcmd_move_tutor.c and
files/fielddata/wazaoshie/waza_oshie.json) for src/overlay005/complete_move_tutor.c:

- each tutor's moves and their Battle Point prices (HeartGold's sTutorMoves, but its Headbutt, which Ilex Forest's
  tutor teaches: include/data/hgss_field_encounters.h);
- who can learn the moves Platinum's tutors don't teach (13 of the 51): up to Arceus, HeartGold's own list; after it, a
  species that learns the move by level or as an egg move (as for Headbutt, tools/complete/import_hgss_field_encounters.py).
  Platinum's 38 the engine's own tutor data decides (each species' learnset by_tutor, res/pokemon).

Writes decomp/include/data/hgss_frontier_tutors.h. From the repo root:
    python3 tools/complete/import_hgss_tutors.py
"""
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
DECOMP = os.path.join(ROOT, 'decomp')
HG = os.path.join(ROOT, '.cache', 'pokeheartgold')
OUT = os.path.join(DECOMP, 'include', 'data', 'hgss_frontier_tutors.h')
TUTORS = {'FRONTIER_TOP_LEFT': 0, 'FRONTIER_TOP_RIGHT': 1, 'FRONTIER_BOTTOM_RIGHT': 2}


def main():
    source = open(os.path.join(HG, 'src', 'field', 'scrcmd_move_tutor.c')).read()
    moves = [(move, int(cost), TUTORS[tutor]) for move, cost, tutor in
             re.findall(r'\{ (MOVE_\w+),\s+(\d+),\s+MOVE_TUTOR_NPC_(\w+)\s*\}', source) if tutor in TUTORS]
    platinum = {m['move'] for m in json.load(open(os.path.join(DECOMP, 'res', 'pokemon', 'move_tutors.json')))}
    others = [move for move, _, _ in moves if move not in platinum]
    assert len(others) <= 16, others

    known = [line.strip() for line in open(os.path.join(DECOMP, 'generated', 'species.txt')) if line.strip()]
    numbers = {name: i for i, name in enumerate(known)}
    masks = [0] * len(known)
    for entry in json.load(open(os.path.join(HG, 'files', 'fielddata', 'wazaoshie', 'waza_oshie.json')))['tutor']:
        if entry['mon'] in numbers:
            for i, move in enumerate(others):
                if 'TUTOR_' + move[len('MOVE_'):] in entry['moves']:
                    masks[numbers[entry['mon']]] |= 1 << i
    arceus = numbers['SPECIES_ARCEUS']
    for path in glob.glob(os.path.join(DECOMP, 'res', 'pokemon', '*', 'data.json')):
        name = 'SPECIES_' + os.path.basename(os.path.dirname(path)).upper()
        if name not in numbers or numbers[name] <= arceus:
            continue
        data = json.load(open(path))
        learnset = data.get('learnset', {})
        learned = {move for _, move in learnset.get('by_level', [])} | set(data.get('egg_moves', [])) | \
            set(learnset.get('egg_moves', []))
        for i, move in enumerate(others):
            if move in learned:
                masks[numbers[name]] |= 1 << i

    out = ['// Generated by tools/complete/import_hgss_tutors.py: HeartGold\'s Battle Frontier move tutors', '// (src/overlay005/complete_move_tutor.c). Do not edit.', '',
           '#ifndef POKEPLATINUM_DATA_HGSS_FRONTIER_TUTORS_H', '#define POKEPLATINUM_DATA_HGSS_FRONTIER_TUTORS_H', '',
           '#include "generated/moves.h"', '',
           '// Each tutor\'s moves: the move, its price in Battle Points and the tutor (HeartGold\'s order)',
           'static const struct {', '    u16 move;', '    u8 cost;', '    u8 tutor;', '} sFrontierTutorMoves[] = {']
    out += [f'    {{ {move}, {cost}, {tutor} }},' for move, cost, tutor in moves]
    out += ['};', '', '// The moves Platinum\'s tutors don\'t teach, a bit each in sFrontierTutorLearners',
            'static const u16 sFrontierTutorOnlyMoves[] = {']
    out += [f'    {move},' for move in others]
    out += ['};', '', '// For each species, which of sFrontierTutorOnlyMoves it can learn',
            f'static const u16 sFrontierTutorLearners[{len(known)}] = {{']
    for start in range(0, len(masks), 12):
        out.append('    ' + ' '.join(f'0x{m:04X},' for m in masks[start:start + 12]))
    out += ['};', '', '#endif // POKEPLATINUM_DATA_HGSS_FRONTIER_TUTORS_H', '']
    open(OUT, 'w').write('\n'.join(out))
    print(f'{OUT}: {len(moves)} moves, {len(others)} of HeartGold\'s own, {sum(1 for m in masks if m)} species learn '
          f'one of those')


if __name__ == '__main__':
    main()
