#!/usr/bin/env python3
"""Write decomp/include/data/complete_pokeathlon_sounds.h: HeartGold's sound numbers as Complete's, for the sound
shims of the Pokéathlon's HeartGold assembly (src/applications/complete_pokeathlon/hgss_compat_course.c).

HeartGold's assembly passes its own sequence numbers (pret's include/constants/sndseq.h) to PlaySE, PlayBGM and the
like; Complete's sound archive numbers its sounds otherwise (decomp/build/res/sound/pl_sound_data.naix). Each of
HeartGold's sound effects and fanfares (SEQ_SE_*, SEQ_ME_*) and the Pokéathlon's songs (SEQ_GS_PT_*) whose name
Complete's archive has (or Platinum's name for it, tools/complete/hgss_script_table.py's SOUNDS) gets a line, sorted
by HeartGold's number; one it lacks plays nothing. The ones the course names and Complete's archive lacks are listed
in the header (the Pokéathlon's own effects and songs: tools/complete/import_hgss_sound.py brings HeartGold's in, then
rerun this).

Usage, after a build (it reads the build's naix): python3 tools/complete/gen_pokeathlon_sounds.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hgss_asm_symbols import ROOT, cache_root  # noqa: E402
from hgss_script_table import SOUNDS  # noqa: E402

HG = os.path.join(cache_root(), '.cache/pokeheartgold')
NAIX = os.path.join(ROOT, 'decomp/build/res/sound/pl_sound_data.naix')
OUT = os.path.join(ROOT, 'decomp/include/data/complete_pokeathlon_sounds.h')
ASM = [os.path.join(ROOT, 'decomp/asm/complete_hgss', f) for f in ('overlay_96.s', 'overlay_97.s', 'overlay_98.s')]
SOUND_CALLS = {'PlaySE': 'r0', 'PlayBGM': 'r0', 'StopBGM': 'r0', 'StopSE': 'r0', 'PlaySE_SetPitch': 'r0',
               'IsSEPlaying': 'r0', 'PlayFanfare': 'r0', 'Sound_SetSceneAndPlayBGM': 'r1', 'sub_0200606C': 'r0',
               'sub_02006118': 'r0', 'sub_0200592C': 'r0', 'sub_02005B78': 'r0'}


def named_constants(path):
    """The constant sound numbers the assembly passes to the sound functions (the register set just before)."""
    found = set()
    lines = open(path, encoding='utf-8').read().split('\n')
    for i, line in enumerate(lines):
        m = re.match(r'\s*bl\s+(\w+)', line)
        if not m or m.group(1) not in SOUND_CALLS:
            continue
        reg = SOUND_CALLS[m.group(1)]
        shifts = []
        for j in range(i - 1, max(i - 30, 0), -1):
            if re.match(r'^\w+:', lines[j]) or re.match(r'\s*(bl|b|bx|pop)\b', lines[j]):
                break
            k = re.match(rf'\s*lsl {reg}, {reg}, #(\d+)', lines[j])
            if k:
                shifts.append(int(k.group(1)))
                continue
            k = re.match(rf'\s*(?:mov {reg}, #|ldr {reg}, _\w+ ; =)(0x[0-9A-Fa-f]+|\d+)\s*$', lines[j])
            if k:
                value = int(k.group(1), 0)
                for s in shifts:
                    value <<= s
                found.add(value)
                break
            if re.match(rf'\s*\w+\s+{reg}\s*,', lines[j]) and not re.match(r'\s*(str|cmp|tst)', lines[j]):
                break
    return found


def hgss_sounds():
    """HeartGold's sound numbers and names (pret's sndseq.h), the first name for a number."""
    hg = {}
    for m in re.finditer(r'#define\s+(SEQ_\w+)\s+(\d+)', open(os.path.join(HG, 'include/constants/sndseq.h')).read()):
        hg.setdefault(int(m.group(2)), m.group(1))
    return hg


def course_sound_names():
    """The names of HeartGold's sounds the Pokéathlon's assembly plays (its effects, fanfares and own songs), for
    tools/complete/import_hgss_sound.py to bring in."""
    used = set()
    for path in ASM:
        if os.path.exists(path):
            used |= named_constants(path)
    return {name for number, name in hgss_sounds().items() if number in used
            and name.startswith(('SEQ_SE_', 'SEQ_ME_', 'SEQ_GS_PT_'))}


def main():
    hg = hgss_sounds()
    if not os.path.exists(NAIX):
        sys.exit(f'{NAIX} missing: build first')
    naix = {m.group(1): int(m.group(2)) for m in re.finditer(r'#define\s+(\w+)\s+(\d+)', open(NAIX).read())}
    table, missing = [], []
    used = set()
    for path in ASM:
        if os.path.exists(path):
            used |= named_constants(path)
    for number, name in sorted(hg.items()):
        if not (name.startswith('SEQ_SE_') or name.startswith('SEQ_ME_') or name.startswith('SEQ_GS_PT_')):
            continue
        ours = SOUNDS.get(name) if name in SOUNDS else name + '_sseq'
        if ours in naix:
            table.append((number, ours, name))
        elif number in used:
            missing.append((number, name))
    lines = [
        '#ifndef POKEPLATINUM_DATA_COMPLETE_POKEATHLON_SOUNDS_H',
        '#define POKEPLATINUM_DATA_COMPLETE_POKEATHLON_SOUNDS_H',
        '',
        '#include "res/sound/pl_sound_data.naix"',
        '',
        '// Sovereign Complete: generated by tools/complete/gen_pokeathlon_sounds.py. HeartGold\'s sound numbers (its',
        '// sndseq.h) and Complete\'s for the same sound (by name: the archive\'s numbers move), by HeartGold\'s number,',
        '// for the Pokéathlon\'s HeartGold assembly (src/applications/complete_pokeathlon/hgss_compat_course.c); a',
        '// number not here plays nothing.',
        '//',
        f'// The course names {len(missing)} that Complete\'s sound archive lacks yet (they play nothing):',
    ]
    for i in range(0, len(missing), 4):
        lines.append('//   ' + ', '.join(f'{name} ({number})' for number, name in missing[i:i + 4]))
    lines += ['', f'#define COMPLETE_POKEATHLON_SOUNDS {len(table)}', '',
              'static const u16 sCompletePokeathlonSounds[COMPLETE_POKEATHLON_SOUNDS][2] = {']
    lines += [f'    {{ {number}, {ours} }}, // {name}' for number, ours, name in table]
    lines += ['};', '', '#endif // POKEPLATINUM_DATA_COMPLETE_POKEATHLON_SOUNDS_H', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'{len(table)} sounds -> {os.path.relpath(OUT, ROOT)}; {len(missing)} the course names are missing')


if __name__ == '__main__':
    main()
