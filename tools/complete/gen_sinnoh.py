#!/usr/bin/env python3
"""Write decomp/include/data/complete_sinnoh.h from data/complete/sinnoh.yaml: Sinnoh as the third region (its levels
after Kanto, its trainers' teams evolved to match, the level caps of all three regions), for src/complete_sinnoh.c and
src/level_cap.c. The Sinnoh part of the caps is Sovereign's list (data/level_caps.yaml), its levels moved up.

Usage: python3 tools/complete/gen_sinnoh.py
"""
import os

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'decomp', 'include', 'data', 'complete_sinnoh.h')
MAX_TRAINERS = 6


def moved(points, level):
    """The level here for Sovereign's level (straight between the plan's points)."""
    for (a, b), (c, e) in zip(points, points[1:]):
        if a <= level <= c:
            return b + ((level - a) * (e - b) * 2 + (c - a)) // ((c - a) * 2)  # half up, as CompleteSinnoh_Level
    return points[-1][1] if level > points[-1][0] else points[0][1]


def main():
    plan = yaml.safe_load(open(os.path.join(ROOT, 'data', 'complete', 'sinnoh.yaml'), encoding='utf-8'))
    sovereign = yaml.safe_load(open(os.path.join(ROOT, 'data', 'level_caps.yaml'), encoding='utf-8'))
    points = plan['levels']
    steps = []
    for cap in plan['caps']:
        steps.append((cap['trainers'], 'LEVEL_CAP_ALL', cap['level'], cap['label']))
    for cap in sovereign['caps']:
        trainers = cap.get('trainers') or cap.get('any')
        steps.append((trainers, 'LEVEL_CAP_ALL' if 'trainers' in cap else 'LEVEL_CAP_ANY', moved(points, cap['level']),
                      cap['label']))
    rows = []
    for trainers, mode, level, label in steps:
        ids = (trainers + ['TRAINER_NONE'] * MAX_TRAINERS)[:MAX_TRAINERS]
        rows.append(f'    {{ {{ {", ".join(ids)} }}, {mode}, {level} }}, // {label}')
    text = '\n'.join([
        '// Generated by tools/complete/gen_sinnoh.py from data/complete/sinnoh.yaml. Do not edit.',
        '#ifndef POKEPLATINUM_DATA_COMPLETE_SINNOH_H',
        '#define POKEPLATINUM_DATA_COMPLETE_SINNOH_H',
        '',
        '#include "data/level_caps.h"',
        '#include "generated/trainers.h"',
        '',
        '// Sovereign\'s level -> the level here, straight between these points',
        'static const u8 sCompleteSinnohLevels[][2] = {',
        *[f'    {{ {a}, {b} }},' for a, b in points],
        '};',
        '',
        f'#define COMPLETE_SINNOH_EVOLVE_FIRST {plan["evolve_at"][0]}',
        f'#define COMPLETE_SINNOH_EVOLVE_SECOND {plan["evolve_at"][1]}',
        f'#define COMPLETE_SINNOH_EVOLVE_WILD {"TRUE" if plan.get("evolve_wild") else "FALSE"}',
        '',
        '// The level caps of all three regions, in story order (src/level_cap.c)',
        'static const LevelCapStep sCompleteLevelCapSteps[] = {',
        *rows,
        '};',
        '',
        '#endif // POKEPLATINUM_DATA_COMPLETE_SINNOH_H',
        '',
    ])
    if not os.path.exists(OUT) or open(OUT, encoding='utf-8').read() != text:
        open(OUT, 'w', encoding='utf-8').write(text)
    print(f'{os.path.relpath(OUT, ROOT)}: {len(points)} level points, {len(rows)} level cap steps; Roark at '
          f'{moved(points, 16)}, Cynthia at {moved(points, 78)}')


if __name__ == '__main__':
    main()
