#!/usr/bin/env python3
"""Give Johto's and Kanto's bosses their Megas (the owner's call, Nov 1, 2026: Megas in all three regions;
docs/Features.md, "Megas in Johto and Kanto"), as Sovereign gives Sinnoh's big fights theirs.

A trainer Mega Evolves the Pokémon holding its Mega Stone (BattleSystem_SovereignMegaForm, once a battle), so each boss
fought after the player's Mega Ring (Whitney, Johto's third Gym Leader, as Fantina is Sinnoh's third) holds one: the
Gym Leaders, the Elite Four, the Champion, Team Rocket's executives, the rival and Red, in every battle whose strongest
Pokémon is above Whitney's ace (Lv. 24), and so after her. The Pokémon is the team's ace when it has a Mega
(data/megas.csv), or else the strongest one that has; its held item becomes that Mega's stone (the first of two, such
as Charizardite X). A boss with no Pokémon that has a Mega keeps its team.

Edits Sacred Gold's trainers in decomp/res/trainers/data/hgss_*.json in place (run it again after
tools/complete/import_hgss_trainers.py) and lists them in docs/BossMegas.md.

Usage: python3 tools/complete/gen_boss_megas.py
"""
import csv
import glob
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TRAINERS = os.path.join(ROOT, 'decomp', 'res', 'trainers', 'data')
BOSS = re.compile(r'^hgss_(leader_|elite_four_|champion_|executive_|rival_|pkmn_trainer_red)')
AFTER_LEVEL = 24  # Whitney's ace: the Mega Ring comes with her badge
SKIP = {'Mega Rayquaza'}  # Rayquaza needs Dragon Ascent, not a stone


def constant(name, prefix):
    return prefix + re.sub(r'_+', '_', re.sub(r'[^A-Z0-9]', '_', name.upper().replace('É', 'E'))).strip('_')


def main():
    items = set(open(os.path.join(ROOT, 'decomp', 'generated', 'items.txt')).read().split())
    stones = {}
    for row in csv.DictReader(open(os.path.join(ROOT, 'data', 'megas.csv'), encoding='utf-8')):
        if row['form'] in SKIP or not row['trigger_item']:
            continue
        species = constant(row['base_species'], 'SPECIES_')
        item = constant(row['trigger_item'], 'ITEM_')
        if item in items:
            stones.setdefault(species, (row['form'], item))
    rows = []
    for path in sorted(glob.glob(os.path.join(TRAINERS, 'hgss_*.json'))):
        name = os.path.basename(path)[:-5]
        if not BOSS.match(name):
            continue
        data = json.load(open(path, encoding='utf-8'))
        party = data.get('party') or []
        if not party or max(p['level'] for p in party) <= AFTER_LEVEL:
            continue
        ace = max(range(len(party)), key=lambda i: (party[i]['level'], i))
        megas = [i for i in range(len(party)) if party[i]['species'] in stones]
        if not megas:
            rows.append((name, data['name'], '—', '—', 'no Pokémon on the team has a Mega'))
            continue
        pick = ace if ace in megas else max(megas, key=lambda i: (party[i]['level'], i))
        form, stone = stones[party[pick]['species']]
        old = party[pick].get('item', 'ITEM_NONE')
        if old != stone:
            party[pick]['item'] = stone
            with open(path, 'w', encoding='utf-8') as f:
                f.write(json.dumps(data, indent=4, ensure_ascii=False) + '\n')
        rows.append((name, data['name'], f'{form} (Lv. {party[pick]["level"]})', stone,
                     'the ace' if pick == ace else 'its strongest with a Mega'))
    lines = ['# Bosses\' Megas in Johto and Kanto', '',
             'Generated by `tools/complete/gen_boss_megas.py`. Each boss fought after the Mega Ring (Whitney) holds a '
             'Mega Stone and Mega Evolves, as Sinnoh\'s big fights do in Sovereign.', '',
             '| Trainer file | Trainer | Mega | Stone | Why |', '|---|---|---|---|---|']
    lines += [f'| `{n}` | {t} | {m} | {s} | {w} |' for n, t, m, s, w in rows]
    open(os.path.join(ROOT, 'docs', 'BossMegas.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{sum(1 for r in rows if r[3] != "—")} of {len(rows)} bosses after the Mega Ring Mega Evolve')


if __name__ == '__main__':
    main()
