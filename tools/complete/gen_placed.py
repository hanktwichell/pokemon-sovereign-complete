#!/usr/bin/env python3
"""Write decomp/include/data/complete_placed.h from data/complete/placed.yaml: Sovereign's Totem trials and
legendaries placed on other maps than Sovereign put them (the owner's call, Nov 1, 2026: spread over Johto, Kanto and
Sinnoh; src/complete_placed.c puts them on their maps).

The plan's two lists:
- moved: [map header, the object's LOCALID_* name in that map's events]: an object of Sovereign's that moves away, so
  it's taken off its map.
- placed: each Totem trial (totem: TOTEM_TRIAL_*, with level: the Totem's new level, its helpers two below) or legendary
  (legendary: SPECIES_*, level), on map at [x, z] (as the map's events give positions), facing dir (0 north, 1 south,
  2 west, 3 east), shown while all its gates hold: flag, flag_clear, var: [VAR, at least], badge (BADGE_ID_*),
  hgss_badge (BADGE_ID_HGSS_*), caught (SPECIES_*), item (ITEM_*), party (SPECIES_*), night: true.

Each placed spot is checked: on the map, walkable, and with nobody else on it.

Usage: python3 tools/complete/gen_placed.py
"""
import json
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DECOMP = os.path.join(ROOT, 'decomp')
PLAN = os.path.join(ROOT, 'data', 'complete', 'placed.yaml')
OUT = os.path.join(DECOMP, 'include', 'data', 'complete_placed.h')
sys.path.insert(0, os.path.join(ROOT, 'tools', 'test'))
from check_object_tiles import Maps, walkable  # noqa: E402

GATES = {'flag': 'PLACED_GATE_FLAG', 'flag_clear': 'PLACED_GATE_FLAG_CLEAR', 'var': 'PLACED_GATE_VAR',
         'badge': 'PLACED_GATE_BADGE', 'hgss_badge': 'PLACED_GATE_HGSS_BADGE', 'caught': 'PLACED_GATE_CAUGHT',
         'item': 'PLACED_GATE_ITEM', 'party': 'PLACED_GATE_PARTY', 'night': 'PLACED_GATE_NIGHT'}


def headers():
    """{map header: (events file, map matrix)}."""
    src = open(os.path.join(DECOMP, 'include', 'data', 'map_headers.h'), encoding='utf-8').read()
    out = {}
    for m in re.finditer(r'\[(MAP_HEADER_\w+)\]\s*=\s*\{(.*?)\}', src, re.S):
        out[m.group(1)] = (re.search(r'eventsArchiveID = (\w+)', m.group(2)).group(1),
                           re.search(r'mapMatrixID = (\w+)', m.group(2)).group(1))
    return out


def events(name):
    return json.load(open(os.path.join(DECOMP, 'res', 'field', 'events', name + '.json'), encoding='utf-8'))


def main():
    plan = yaml.safe_load(open(PLAN, encoding='utf-8'))
    maps_of = headers()
    gfx = set(open(os.path.join(DECOMP, 'generated', 'object_events_gfx.txt')).read().split())
    tiles = Maps(DECOMP)
    rows, moved, problems = [], [], []

    for header, local in plan.get('moved') or []:
        objects = events(maps_of[header][0])['object_events']
        ids = [o.get('id') for o in objects]
        if local not in ids:
            problems.append(f'{header} has no {local}')
            continue
        moved.append(f'    {{ {header}, {ids.index(local)} }}, // {local}')

    levels = {}
    for i, p in enumerate(plan.get('placed') or []):
        header = p['map']
        x, z = p['at']
        if 'totem' in p:
            kind, value = 'PLACED_TOTEM', p['totem']
            graphics = 'OBJ_EVENT_GFX_TOTEM_' + value[len('TOTEM_TRIAL_'):]
            level = p.get('level', 0)
            if level:
                levels[value] = level
        else:
            kind, value = 'PLACED_LEGENDARY', p['legendary']
            graphics = p.get('gfx', 'OBJ_EVENT_GFX_LEGENDARY_' + value[len('SPECIES_'):])
            level = p['level']
        if graphics not in gfx:
            problems.append(f'{value}: no {graphics}')
        # the spot: on the map, walkable, nobody there
        ev, matrix = maps_of[header]
        tile = tiles.tile(matrix, x, z)
        if tile is None or not walkable(tile):
            problems.append(f'{value} on {header} ({x}, {z}): not a walkable tile')
        if any(o['x'] == x and o['z'] == z for o in events(ev)['object_events']):
            problems.append(f'{value} on {header} ({x}, {z}): someone stands there')
        gates = []
        for gate in p.get('gates') or []:
            (key, arg), = gate.items()
            if key == 'var':
                gates.append(f'{{ {GATES[key]}, {arg[0]}, {arg[1]} }}')
            elif key == 'night':
                gates.append(f'{{ {GATES[key]}, 0, 0 }}')
            else:
                gates.append(f'{{ {GATES[key]}, {arg}, 0 }}')
        if len(gates) > 4:
            problems.append(f'{value}: more than four gates')
        rows.append(f'    {{ {header}, {x}, {z}, {graphics}, {value}, {kind}, {level}, {p.get("dir", 1)}, {len(gates)}, '
                    f'{{ {", ".join(gates)} }} }},')

    if problems:
        sys.exit('\n'.join(problems))
    totem_levels = ', '.join(f'[{t}] = {lv}' for t, lv in levels.items())
    text = '\n'.join([
        '// Generated by tools/complete/gen_placed.py from data/complete/placed.yaml. Do not edit.',
        '#ifndef POKEPLATINUM_DATA_COMPLETE_PLACED_H',
        '#define POKEPLATINUM_DATA_COMPLETE_PLACED_H',
        '',
        '#include "constants/hgss_badges.h"',
        '#include "constants/sovereign_totem_trials.h"',
        '#include "generated/badges.h"',
        '#include "generated/items.h"',
        '#include "generated/map_headers.h"',
        '#include "generated/object_events_gfx.h"',
        '#include "generated/species.h"',
        '#include "generated/vars_flags.h"',
        '',
        '#include "complete_placed.h"',
        '',
        'static const CompletePlaced sCompletePlaced[] = {',
        *rows,
        '    { 0xFFFF }, // none: the list may be empty',
        '};',
        '',
        'static const CompletePlacedMoved sCompletePlacedMoved[] = {',
        *moved,
        '    { 0xFFFF, 0xFFFF }, // none',
        '};',
        '',
        '// A moved Totem\'s new level (0: Sovereign\'s), by trial',
        f'static const u8 sCompletePlacedTotemLevels[SOVEREIGN_TOTEM_TRIAL_COUNT] = {{ {totem_levels} }};',
        '',
        '#endif // POKEPLATINUM_DATA_COMPLETE_PLACED_H',
        '',
    ])
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if text != old:
        with open(OUT, 'w', encoding='utf-8') as f:
            f.write(text)
    print(f'{os.path.relpath(OUT, ROOT)}: {len(rows)} placed, {len(moved)} moved')


if __name__ == '__main__':
    main()
