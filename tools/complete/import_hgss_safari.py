#!/usr/bin/env python3
"""Write HeartGold's Johto Safari Zone tables for src/complete_safari.c.

From HeartGold's source (Sacred Gold's ROM has the same bytes, docs/Features.md):
- The encounters (decomp/res/prebuilt/fielddata/complete_safari/safari_encounters.narc,
  NARC_INDEX_FIELDDATA__COMPLETE__SAFARI_ENCOUNTERS, read as they're needed so that the main module, whose memory the
  test build has almost none of to spare, doesn't hold them): a member for each of the 12 areas, in
  SAFARI_ZONE_AREA_* order, of five SafariEncounters (include/complete_safari.h), one for each encounter type (land,
  surf, Old, Good and Super Rod): the ten base slots at morning, day and night (files/arc/safari_enc.json), and the
  bonus slots, each with its Pokémon at the three times and the objects it needs (one or two object types, each at a
  level; HeartGold's json calls it count).
- sSafariDefaultAreaSets: the ten arrangements a new game picks one of (src/safari_zone.c), as C
  (decomp/include/data/complete_safari.h).

Usage, from the repo root: python3 tools/complete/import_hgss_safari.py
"""
import json
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_hgss_headers import write_if_changed  # noqa: E402
from import_hgss_maps import DECOMP, HG  # noqa: E402
from narc import write_narc  # noqa: E402

OUT = 'include/data/complete_safari.h'
NARC_DIR = os.path.join('res', 'prebuilt', 'fielddata', 'complete_safari')
ENCOUNTERS_SIZE = 282  # sizeof(SafariEncounters): 30 slots of 4 bytes, the count and a pad, 10 bonus slots of 16
TYPES = ['land', 'surf', 'oldrod', 'goodrod', 'superrod']
TIMES = ['morn', 'day', 'nite']
SLOTS = 10
MAX_BONUS = 10


def default_sets():
    text = open(os.path.join(HG, 'src', 'safari_zone.c')).read()
    block = re.search(r'sSafariZoneDefaultAreaSets\[10\]\[SAFARI_ZONE_MAX_AREAS_PER_SET\] = \{(.*?)\n\};', text, re.S)
    return [re.findall(r'SAFARI_ZONE_AREA_\w+', row) for row in re.findall(r'\{([^{}]*)\}', block.group(1))]


def enum_values(prefix):
    """The values of an enum's members in include/complete_safari.h, by name."""
    text = open(os.path.join(DECOMP, 'include', 'complete_safari.h')).read()
    values, n = {}, 0
    for name, value in re.findall(rf'^\s+({prefix}\w+)(?: = (\w+))?,', text, re.M):
        n = int(value) if value and value.isdigit() else values.get(value, n) if value else n
        values[name] = n
        n += 1
    return values


def packed(data, species, objects):
    """One SafariEncounters, as the game lays it out (include/complete_safari.h)."""
    out = bytearray()
    for t in TIMES:
        for mon in data['mons'][t]:
            out += struct.pack('<HBx', species.index(mon['species']), mon['level'])
    bonus = data.get('bonus_mons', [])
    out += struct.pack('<Bx', len(bonus))
    for b in bonus + [None] * (MAX_BONUS - len(bonus)):
        if b is None:
            out += bytes(16)
            continue
        for t in TIMES:
            out += struct.pack('<HBx', species.index(b[t]['species']), b[t]['level'])
        conds = b['conditions'] + [{'object_type': 'SAFARI_ZONE_OBJECT_TYPE_NONE', 'count': 0}] * (2 - len(b['conditions']))
        for c in conds:
            out += struct.pack('<BB', objects[c['object_type']], c['count'])
    assert len(out) == ENCOUNTERS_SIZE, len(out)
    return bytes(out)


def main():
    areas = json.load(open(os.path.join(HG, 'files', 'arc', 'safari_enc.json')))['encounters']
    species = open(os.path.join(DECOMP, 'generated', 'species.txt')).read().split()
    objects = enum_values('SAFARI_ZONE_OBJECT_TYPE_')
    numbers = enum_values('SAFARI_ZONE_AREA_')
    members = [None] * len(areas)
    most = 0
    for area in areas:
        tables = []
        for kind in TYPES:
            data = area[kind]
            assert all(len(data['mons'][t]) == SLOTS for t in TIMES), (area['area'], kind)
            assert len(data.get('bonus_mons', [])) <= MAX_BONUS, (area['area'], kind)
            most = max(most, len(data.get('bonus_mons', [])))
            tables.append(packed(data, species, objects))
        members[numbers[area['area']]] = b''.join(tables)
    os.makedirs(os.path.join(DECOMP, NARC_DIR), exist_ok=True)
    write_narc(os.path.join(DECOMP, NARC_DIR, 'safari_encounters.narc'), members)
    with open(os.path.join(DECOMP, NARC_DIR, 'meson.build'), 'w', encoding='utf-8') as f:
        f.write("# Sovereign Complete: the Johto Safari Zone's encounters (tools/complete/import_hgss_safari.py,\n"
                "# src/complete_safari.c)\n"
                "nitrofs_files += fs.copyfile('safari_encounters.narc')\n")

    out = ['// Generated by tools/complete/import_hgss_safari.py from HeartGold\'s safari_zone.c; do not edit. (The',
           '// encounters, from its safari_enc.json, are fielddata/complete/safari_encounters.narc.)',
           '#ifndef POKEPLATINUM_DATA_COMPLETE_SAFARI_H',
           '#define POKEPLATINUM_DATA_COMPLETE_SAFARI_H',
           '',
           'static const u8 sSafariDefaultAreaSets[10][SAFARI_ZONE_AREAS_PER_SET] = {']
    for row in default_sets():
        out.append('    { ' + ', '.join(row) + ' },')
    out += ['};', '', '#endif', '']
    write_if_changed(os.path.join(DECOMP, OUT), '\n'.join(out))
    print(f'{OUT} and {NARC_DIR}/safari_encounters.narc: {len(areas)} areas, at most {most} bonus slots in one table')


if __name__ == '__main__':
    main()
