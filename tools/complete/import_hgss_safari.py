#!/usr/bin/env python3
"""Write HeartGold's Johto Safari Zone tables as C (decomp/include/data/complete_safari.h), for src/complete_safari.c.

From HeartGold's source (Sacred Gold's ROM has the same bytes, docs/Features.md):
- sSafariEncounters: for each of the 12 areas and each encounter type (land, surf, Old, Good and Super Rod), the ten
  base slots at morning, day and night (files/arc/safari_enc.json), and its bonus slots, each with its Pokémon at the
  three times and the objects it needs (one or two object types, each at a level; HeartGold's json calls it count).
- sSafariDefaultAreaSets: the ten arrangements a new game picks one of (src/safari_zone.c).

Usage, from the repo root: python3 tools/complete/import_hgss_safari.py
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_hgss_headers import write_if_changed  # noqa: E402
from import_hgss_maps import DECOMP, HG  # noqa: E402

OUT = 'include/data/complete_safari.h'
TYPES = ['land', 'surf', 'oldrod', 'goodrod', 'superrod']
TIMES = ['morn', 'day', 'nite']
SLOTS = 10
MAX_BONUS = 10


def default_sets():
    text = open(os.path.join(HG, 'src', 'safari_zone.c')).read()
    block = re.search(r'sSafariZoneDefaultAreaSets\[10\]\[SAFARI_ZONE_MAX_AREAS_PER_SET\] = \{(.*?)\n\};', text, re.S)
    return [re.findall(r'SAFARI_ZONE_AREA_\w+', row) for row in re.findall(r'\{([^{}]*)\}', block.group(1))]


def slot(mon):
    return f'{{ {mon["species"]}, {mon["level"]} }}'


def main():
    areas = json.load(open(os.path.join(HG, 'files', 'arc', 'safari_enc.json')))['encounters']
    out = ['// Generated by tools/complete/import_hgss_safari.py from HeartGold\'s safari_enc.json and safari_zone.c; do',
           '// not edit.',
           '#ifndef POKEPLATINUM_DATA_COMPLETE_SAFARI_H',
           '#define POKEPLATINUM_DATA_COMPLETE_SAFARI_H',
           '',
           f'static const SafariEncounters sSafariEncounters[{len(areas)}][{len(TYPES)}] = {{']
    most = 0
    for area in areas:
        out.append(f'    [{area["area"]}] = {{')
        for kind in TYPES:
            data = area[kind]
            bonus = data.get('bonus_mons', [])
            most = max(most, len(bonus))
            assert len(bonus) <= MAX_BONUS, (area['area'], kind, len(bonus))
            out.append('        {')
            out.append('            .base = {')
            for t in TIMES:
                mons = data['mons'][t]
                assert len(mons) == SLOTS, (area['area'], kind, t)
                out.append('                { ' + ', '.join(slot(m) for m in mons) + ' },')
            out.append('            },')
            out.append(f'            .bonusCount = {len(bonus)},')
            if bonus:
                out.append('            .bonus = {')
                for b in bonus:
                    conds = b['conditions'] + [{'object_type': 'SAFARI_ZONE_OBJECT_TYPE_NONE', 'count': 0}] * (2 - len(b['conditions']))
                    need = ', '.join(f'{{ {c["object_type"]}, {c["count"]} }}' for c in conds)
                    mons = ', '.join(slot(b[t]) for t in TIMES)
                    out.append(f'                {{ {{ {mons} }}, {{ {need} }} }},')
                out.append('            },')
            out.append('        },')
        out.append('    },')
    out += ['};', '', f'static const u8 sSafariDefaultAreaSets[10][SAFARI_ZONE_AREAS_PER_SET] = {{']
    for row in default_sets():
        out.append('    { ' + ', '.join(row) + ' },')
    out += ['};', '', '#endif', '']
    write_if_changed(os.path.join(DECOMP, OUT), '\n'.join(out))
    print(f'{OUT}: {len(areas)} areas, at most {most} bonus slots in one table')


if __name__ == '__main__':
    main()
