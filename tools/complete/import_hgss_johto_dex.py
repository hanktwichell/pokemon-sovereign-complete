#!/usr/bin/env python3
"""Bring in HeartGold's Johto Pokédex list (its poketool/johtozukan.narc: the Johto number of each species #0-493, 0 for
none), as decomp/include/data/hgss_johto_dex.h: the 256 species in Johto order, and each species' Johto number (#0-493,
0 for none). src/complete_pokedex.c reads both: Johto's is the regional Pokédex until Sinnoh's story begins, and the
Celadon Condominiums' game designer checks it's complete.

Usage: python3 tools/complete/import_hgss_johto_dex.py
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_hgss_maps import DECOMP, HG  # noqa: E402
from narc import read_narc  # noqa: E402

OUT = os.path.join(DECOMP, 'include/data/hgss_johto_dex.h')


def main():
    data = read_narc(os.path.join(HG, 'files/poketool/johtozukan.narc'))[0]
    johto = struct.unpack(f'<{len(data) // 2}H', data)
    species = [line.strip() for line in open(os.path.join(DECOMP, 'generated/species.txt')) if line.strip()]
    order = sorted((n, s) for s, n in enumerate(johto) if n)
    assert [n for n, _ in order] == list(range(1, len(order) + 1)), 'the Johto numbers run 1 on'
    lines = [
        '#ifndef POKEPLATINUM_DATA_HGSS_JOHTO_DEX_H',
        '#define POKEPLATINUM_DATA_HGSS_JOHTO_DEX_H',
        '',
        '// Generated by tools/complete/import_hgss_johto_dex.py: HeartGold\'s Johto Pokédex, in its order',
        '',
        '#include "generated/species.h"',
        '',
        'static const u16 sHGSSJohtoDex[] = {',
        *(f'    {species[s]},' for _, s in order),
        '};',
        '',
        '// Each species\' Johto number, 0 for none',
        'static const u16 sHGSSJohtoDexNumbers[] = {',
        *(f'    [{species[s]}] = {n},' for s, n in enumerate(johto) if n),
        f'    [{species[len(johto) - 1]}] = {johto[-1]},' if not johto[-1] else '',
        '};',
        '',
        '#endif // POKEPLATINUM_DATA_HGSS_JOHTO_DEX_H',
        '',
    ]
    open(OUT, 'w').write('\n'.join(lines))
    print(f'{len(order)} species')


if __name__ == '__main__':
    main()
