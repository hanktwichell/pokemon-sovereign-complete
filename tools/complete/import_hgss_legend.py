#!/usr/bin/env python3
"""Bring in HeartGold's legendary cutscenes' graphics (its files/demo/legend, which src/field/legend_cutscene_camera.c
loads) for src/overlay005/complete_legend_cutscene.c: the Clear Bell rising and shimmering, the corner bells, the
Lugia's eye glint, the circle round the bird as it lands, the waves (Whirl Islands) and the leaves (the Bell Tower's
roof: their tiles, palette and twelve tilemaps). Members 18 to 54 of HeartGold's archive, the ones the cutscenes use,
are packed as they are, in order, into decomp/res/prebuilt/fielddata/complete_legend/legend.narc
(NARC_INDEX_FIELDDATA__COMPLETE__LEGEND), so HeartGold's member n is n - LEGEND_FIRST_MEMBER there
(include/data/hgss_legend.h).

Usage: python3 tools/complete/import_hgss_legend.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_hgss_maps import DECOMP, HG  # noqa: E402
from narc import write_narc  # noqa: E402

SOURCE = os.path.join(HG, 'files', 'demo', 'legend')
OUT = os.path.join(DECOMP, 'res', 'prebuilt', 'fielddata', 'complete_legend')
HEADER = os.path.join(DECOMP, 'include', 'data', 'hgss_legend.h')
FIRST, LAST = 18, 54


def main():
    names = sorted(f for f in os.listdir(SOURCE) if f.startswith('legend_'))
    by_number = {int(f[len('legend_'):len('legend_') + 8]): f for f in names}
    members = [open(os.path.join(SOURCE, by_number[n]), 'rb').read() for n in range(FIRST, LAST + 1)]
    os.makedirs(OUT, exist_ok=True)
    write_narc(os.path.join(OUT, 'legend.narc'), members)
    with open(HEADER, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/complete/import_hgss_legend.py: HeartGold\'s legendary cutscenes\' graphics (its\n'
                '// files/demo/legend), members ' + f'{FIRST} to {LAST}' + ' packed in order into legend.narc. Do not edit.\n\n'
                '#ifndef POKEPLATINUM_DATA_HGSS_LEGEND_H\n#define POKEPLATINUM_DATA_HGSS_LEGEND_H\n\n'
                f'#define LEGEND_FIRST_MEMBER {FIRST}\n'
                '#define LEGEND_MEMBER(hgssMember) ((hgssMember) - LEGEND_FIRST_MEMBER) // HeartGold\'s legend_000000NN\n\n'
                '#endif // POKEPLATINUM_DATA_HGSS_LEGEND_H\n')
    with open(os.path.join(OUT, 'meson.build'), 'w', encoding='utf-8') as f:
        f.write('# Sovereign Complete: HeartGold\'s legendary cutscenes\' graphics (tools/complete/import_hgss_legend.py,\n'
                '# src/overlay005/complete_legend_cutscene.c)\n'
                "nitrofs_files += fs.copyfile('legend.narc')\n")
    size = sum(len(m) for m in members)
    print(f'legend.narc: {len(members)} files ({size // 1024} KB) from members {FIRST}-{LAST} of {SOURCE}')


if __name__ == '__main__':
    main()
